// Renders supabase/migrations/*.sql for a dedicated schema, so Homed can live inside a Supabase
// project that another app already uses without touching that app's `public` tables or grants.
//
//   npx tsx packages/db/scripts/render-migrations.ts homed > homed.sql
//
// Tables go to <schema>, RLS helper functions to <schema>_private. The storage bucket insert is
// dropped (documents are stored encrypted in a table column). Then expose <schema> to the Data API
// (Dashboard > Settings > API > Exposed schemas) and set HOMED_SUPABASE_SCHEMA=<schema>.
import { readdirSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export function renderForSchema(sql: string, schema: string): string {
  if (!/^[a-z_][a-z0-9_]*$/.test(schema) || schema === 'public') {
    throw new Error(`schema must be a lowercase identifier other than public, got "${schema}"`);
  }
  const priv = `${schema}_private`;
  return (
    sql
      // Drop the storage bucket (Homed keeps document ciphertext in application_documents).
      .replace(/insert into storage\.buckets[\s\S]*?;\n/g, '')
      .replace(/\bschema if not exists private\b/g, `schema if not exists ${priv}`)
      .replace(/\bschema private\b/g, `schema ${priv}`)
      .replace(/\bprivate\./g, `${priv}.`)
      .replace(/\bschema public\b/g, `schema ${schema}`)
      .replace(/\bpublic\./g, `${schema}.`)
  );
}

export function renderMigrations(dir: string, schema: string): string {
  const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
  const header = [
    `-- Homed migrations rendered for schema "${schema}" (generated by packages/db/scripts/render-migrations.ts).`,
    `create schema if not exists ${schema};`,
    `grant usage on schema ${schema} to anon, authenticated, service_role;`,
    '',
  ].join('\n');
  const body = files.map((f) => `-- ===== ${f} =====\n${renderForSchema(readFileSync(join(dir, f), 'utf8'), schema)}`).join('\n');
  return `${header}\n${body}`;
}

const isMain = process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const schema = process.argv[2];
  if (!schema) {
    console.error('usage: npx tsx packages/db/scripts/render-migrations.ts <schema>');
    process.exit(1);
  }
  const dir = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', 'supabase', 'migrations');
  process.stdout.write(renderMigrations(dir, schema));
}
